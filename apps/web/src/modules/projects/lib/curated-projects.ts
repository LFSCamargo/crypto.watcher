export function filterCuratedProjects(
  query: string,
  projects: CuratedProject[] = curatedProjects,
  category?: CuratedProject['category'],
): CuratedProject[] {
  const normalizedQuery = query.trim().toLowerCase()
  const scopedProjects = category
    ? projects.filter((project) => project.category === category)
    : projects

  if (!normalizedQuery) {
    return scopedProjects
  }

  return scopedProjects.filter((project) =>
    [
      project.name,
      project.symbol,
      project.network,
      project.description,
      project.category,
    ].some((value) => value.toLowerCase().includes(normalizedQuery)),
  )
}

export function getCuratedProject(slug: string): CuratedProject | undefined {
  return curatedProjects.find((project) => project.slug === slug)
}

export function getTopRatedProjects(limit: number): CuratedProject[] {
  return [...curatedProjects].sort((a, b) => b.score - a.score).slice(0, limit)
}
